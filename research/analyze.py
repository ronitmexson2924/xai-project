"""R8: run every pre-registered analysis and write the results report.

    cd backend
    ANALYSIS_SALT=... PYTHONPATH=../research python ../research/analyze.py --from-db   # pilot
    PYTHONPATH=../research python ../research/analyze.py --simulated                  # validation

--from-db reads the pilot database (DATABASE_URL), pseudonymises learners with ANALYSIS_SALT and
writes research/reports/results.md. Keep the salt secret and fixed for the whole study.
--simulated runs the simulator in a rolled-back transaction and writes
research/reports/results_simulated.md. The two are never mixed (EVALUATION_PLAN.md).
"""

import argparse
import os
import secrets
import sys
import time
from pathlib import Path

from analysis import hypotheses as h
from analysis.export import Frames, load_frames
from backtest.early_warning import BacktestConfig, backtest

from app.db.session import SessionLocal
from app.graph.content import load_content
from app.graph.service import GraphSnapshot

REPORTS = Path(__file__).parent / "reports"
CONTENT = Path(__file__).parents[1] / "content"


def f3(x: float) -> str:
    return f"{x:.3f}"


def render(frames: Frames, source: str, n_boot: int) -> str:
    started = time.perf_counter()
    items = load_content(CONTENT).questionnaire
    r1 = h.h1(frames, n_boot=n_boot)
    r2 = h.h2(frames)
    r4 = h.h4(frames, n_boot=n_boot)
    alpha = h.reliability(frames, items)
    cfg = BacktestConfig()
    r5 = backtest(frames, cfg)
    arms = frames.learners.arm.value_counts().to_dict()
    att = frames.attempts

    lines = [
        f"# Results ({source})",
        "",
        "> Generated by `research/analyze.py`. **Do not edit by hand.** Hypotheses and methods "
        "are pre-registered in `research/preregistration.md`.",
        "",
        "## Data",
        "",
        f"- Learners per arm: {', '.join(f'{k} {v}' for k, v in sorted(arms.items()))}.",
        f"- Answers: {int((att.test_phase.isna() & ~att.is_microcheck).sum())} practice, "
        f"{int(att.is_microcheck.sum())} micro-check, {int(att.test_phase.notna().sum())} "
        f"pre/post-test. Explanations shown: {len(frames.explanations)} "
        f"({int(frames.explanations.has_feedback.sum())} with a feedback summary).",
        "",
        "## H1: explanation-interaction features improve next-answer prediction",
        "",
    ]
    if r1["available"]:
        lines += [
            f"{r1['n']} practice answers from {r1['learners']} learners that follow an explanation "
            "on the same concept. 5-fold cross-validation split by learner; logistic regression on "
            "logit(BKT p̂) alone vs. plus the feedback features of the most recent explanation.",
            "",
            "| model | AUC | log-loss |",
            "|---|---|---|",
            f"| BKT p̂ only | {f3(r1['auc_base'])} | {f3(r1['logloss_base'])} |",
            f"| + explanation feedback | {f3(r1['auc_full'])} | {f3(r1['logloss_full'])} |",
            "",
            f"AUC gain {r1['auc_full'] - r1['auc_base']:+.3f} (95% learner-bootstrap CI "
            f"{r1['auc_gain_ci'][0]:+.3f} to {r1['auc_gain_ci'][1]:+.3f}); log-loss reduction "
            f"{r1['logloss_base'] - r1['logloss_full']:+.4f} "
            f"(CI {r1['logloss_gain_ci'][0]:+.4f} to {r1['logloss_gain_ci'][1]:+.4f}). "
            "**H1 is supported only if both CIs exclude 0.**",
        ]
    else:
        lines.append(f"Not enough data ({r1['n']} usable answers).")

    lines += ["", "## H2: arm effect on micro-check accuracy", ""]
    lines += ["| arm | micro-checks | accuracy |", "|---|---|---|"]
    for arm, r in sorted(r2["rates"].items()):
        lines.append(f"| {arm} | {int(r['count'])} | {f3(r['mean'])} |")
    if r2["available"]:
        lines += [
            "",
            "GEE logistic regression (exchangeable correlation within learner), adjusted for "
            "concept cluster; odds ratios vs. generic:",
            "",
            "| arm | odds ratio | 95% CI | p |",
            "|---|---|---|---|",
            *(
                f"| {arm} | {f3(e['odds_ratio'])} | {f3(e['ci'][0])} to {f3(e['ci'][1])} | "
                f"{e['p']:.3g} |"
                for arm, e in sorted(r2["effects"].items())
            ),
        ]

    lines += ["", "## H4: normalised learning gain (pre/post test)", ""]
    if r4["available"]:
        lines += ["| arm | learners | mean gain | 95% CI |", "|---|---|---|---|"]
        for arm, r in sorted(r4["per_arm"].items()):
            lines.append(
                f"| {arm} | {r['n']} | {f3(r['mean'])} | {f3(r['ci'][0])} to {f3(r['ci'][1])} |"
            )
        lines += ["", "| vs. generic | difference | 95% CI | Cohen's d |", "|---|---|---|---|"]
        for arm, d in sorted(r4["vs_generic"].items()):
            lines.append(
                f"| {arm} | {d['diff']:+.3f} | {d['ci'][0]:+.3f} to {d['ci'][1]:+.3f} | "
                f"{d['cohens_d']:+.2f} |"
            )
        lines += [
            "",
            "Pre-registered as underpowered: report the effect size and CI, not a significance "
            "claim.",
        ]
    else:
        lines.append("No pre/post-test data in this export.")

    lines += [
        "",
        "## Questionnaire reliability",
        "",
        "| trait | Cronbach's α | complete respondents |",
        "|---|---|---|",
        *(f"| {t} | {f3(a)} | {n} |" for t, (a, n) in alpha.items()),
        "",
        "## H5 (exploratory): early warning before struggle",
        "",
        "A struggle run = two wrong answers in a row on one concept. A detector warns **early** "
        f"if an alarm started within the {cfg.window} answers up to and including the run's "
        "*first* wrong answer, i.e. before performance visibly dropped. Lead = how many answers "
        "before that first wrong answer the most recent alarm started.",
        "",
        "| detector | struggle runs | early-warning recall | precision | median lead "
        "| alarms / 100 answers |",
        "|---|---|---|---|---|---|",
        *(
            f"| {name} | {r['events']} | {f3(r['recall'])} | {f3(r['precision'])} | "
            f"{r['median_lead']:.1f} | {r['alarms_per_100']:.1f} |"
            for name, r in r5.items()
        ),
        "",
        "A detector is only useful if it beats the naive baseline on lead time *and* "
        "precision; resonance and drift may drive live decisions only if this holds on "
        "pilot data (decision D10).",
        "",
        f"_Analysis time {time.perf_counter() - started:.1f} s._",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--from-db", action="store_true")
    mode.add_argument("--simulated", action="store_true")
    parser.add_argument("--learners", type=int, default=30, help="per arm (--simulated)")
    parser.add_argument("--steps", type=int, default=50, help="per learner (--simulated)")
    parser.add_argument("--bootstrap", type=int, default=1000)
    parser.add_argument("--save-export", type=Path, help="also write the frames as CSV here")
    parser.add_argument("--out", type=Path, default=REPORTS)
    args = parser.parse_args()

    with SessionLocal() as session:
        try:
            if args.simulated:
                from simulator.driver import RunConfig, simulate
                from simulator.population import ResponseConfig

                cfg = RunConfig(
                    learners_per_arm=args.learners,
                    steps=args.steps,
                    seed=5,
                    response=ResponseConfig(self_report_gap=0.2),
                )
                simulate(session, cfg)
                graph = GraphSnapshot.from_db(session, include_drafts=True)
                frames = load_frames(session, graph, salt=secrets.token_hex(8), email_like="%@sim")
                source = (
                    f"SIMULATED validation run: {args.learners} learners per arm, "
                    f"{args.steps} steps, self-report gap 0.2. Not pilot data"
                )
                name = "results_simulated.md"
            else:
                salt = os.environ.get("ANALYSIS_SALT")
                if not salt:
                    print(
                        "set ANALYSIS_SALT (a fixed secret) to pseudonymise learners",
                        file=sys.stderr,
                    )
                    return 1
                graph = GraphSnapshot.from_db(session, include_drafts=True)
                frames = load_frames(session, graph, salt=salt)
                source = "PILOT data"
                name = "results.md"
        finally:
            session.rollback()

    if args.save_export:
        frames.save(args.save_export)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / name).write_text(render(frames, source, args.bootstrap))
    print(f"wrote {args.out / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
