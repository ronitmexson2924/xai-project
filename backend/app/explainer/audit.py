"""Explanation audit and inter-rater reliability (Task M7, EVALUATION_PLAN "System quality").

Owner: Mit.

    python -m app.explainer.audit sample --n 100 --out audit.csv     # 1. draw the sample
    (Mit and Ronit each fill in their own column, independently: correct | minor_issue | wrong)
    python -m app.explainer.audit score audit.csv                    # 2. kappa + report

`sample` generates explanations across concepts and style buckets and records an automatic
grounding check (does the text reuse the concept card's definition or key idea?). The rating
columns are left empty: only people fill them. `score` refuses to run until every row has both
ratings, then writes research/reports/llm_audit.md from those ratings.
"""

import argparse
import csv
import random
import sys
from pathlib import Path
from uuid import uuid4

from app.contracts.explanation import ExplanationRequest, StyleParams
from app.contracts.reasons import ReasonCode, ReasonEvidence
from app.explainer.service import GroundedExplainerService
from app.graph.content import load_content
from app.graph.service import GraphSnapshot

RATINGS = ("correct", "minor_issue", "wrong")
RATER_COLUMNS = ("rater_mit", "rater_ronit")
CONTENT = Path(__file__).resolve().parents[3] / "content"
REPORT = Path(__file__).resolve().parents[3] / "research" / "reports" / "llm_audit.md"


def compute_cohens_kappa(rater1: list[str], rater2: list[str]) -> tuple[float, float, float]:
    """Cohen's kappa between two raters. Returns (kappa, observed, expected agreement)."""
    if len(rater1) != len(rater2) or not rater1:
        raise ValueError("rater lists must be non-empty and of equal length")
    n = len(rater1)
    p_o = sum(a == b for a, b in zip(rater1, rater2, strict=True)) / n
    p_e = sum((rater1.count(c) / n) * (rater2.count(c) / n) for c in set(rater1) | set(rater2))
    if p_e == 1.0:
        return 1.0, p_o, p_e
    return (p_o - p_e) / (1 - p_e), p_o, p_e


def grounded(body: str, definition: str, key_idea: str) -> bool:
    """Automatic check: the text reuses the card's definition or key idea (first 20 chars)."""
    text = body.lower()
    return definition[:20].lower() in text or key_idea[:20].lower() in text


def draw_sample(n: int, seed: int = 42) -> list[dict[str, str]]:
    rng = random.Random(seed)
    graph = GraphSnapshot.from_bundle(load_content(CONTENT))
    explainer = GroundedExplainerService(graph)
    concepts, _ = graph.get_graph()
    rows = []
    for i in range(n):
        concept = concepts[i % len(concepts)]
        style = StyleParams(
            example_first=rng.choice([True, False]),
            length=rng.choice(["short", "medium", "long"]),
            depth=rng.choice(["how", "why"]),
        )
        explanation = explainer.explain(
            ExplanationRequest(
                user_id=uuid4(),
                recommendation_id=uuid4(),
                concept_ids=[concept.id],
                reasons=[ReasonEvidence(code=ReasonCode.READY_FOR_NEXT, concept_id=concept.id)],
                style=style,
                style_source="generic",
            )
        )
        card = concept.card
        rows.append(
            {
                "id": f"audit-{i + 1:03d}",
                "concept_id": concept.id,
                "style_key": style.variant_key(),
                "source": explanation.source,
                "auto_grounded": str(
                    grounded(explanation.body_markdown, card.definition, card.key_idea)
                ),
                "body_markdown": explanation.body_markdown,
                "rater_mit": "",
                "rater_ronit": "",
            }
        )
    return rows


def score(rows: list[dict[str, str]]) -> dict[str, float]:
    """Kappa and rates from completed ratings. Raises ValueError if any rating is missing."""
    for row in rows:
        for column in RATER_COLUMNS:
            if row.get(column, "").strip() not in RATINGS:
                raise ValueError(f"{row.get('id')}: {column} must be one of {', '.join(RATINGS)}")
    mit = [r["rater_mit"].strip() for r in rows]
    ronit = [r["rater_ronit"].strip() for r in rows]
    kappa, p_o, p_e = compute_cohens_kappa(mit, ronit)
    n = len(rows)
    return {
        "n": n,
        "kappa": kappa,
        "observed_agreement": p_o,
        "expected_agreement": p_e,
        "wrong_rate_pct": 100 * sum("wrong" in (a, b) for a, b in zip(mit, ronit, strict=True)) / n,
        "auto_grounded_pct": 100 * sum(r["auto_grounded"] == "True" for r in rows) / n,
    }


def write_report(stats: dict[str, float], source: Path) -> None:
    REPORT.write_text(
        "\n".join(
            [
                "# Explanation audit (inter-rater reliability)",
                "",
                f"> Generated by `python -m app.explainer.audit score {source.name}` from the "
                "ratings two people entered. Do not edit by hand.",
                "",
                f"- Explanations rated: {stats['n']}",
                f"- Cohen's kappa: {stats['kappa']:.3f} (pre-registered target >= 0.85)",
                f"- Observed agreement: {stats['observed_agreement']:.1%}; "
                f"expected by chance: {stats['expected_agreement']:.1%}",
                f"- Rated wrong by at least one rater: {stats['wrong_rate_pct']:.1f}% "
                "(threshold <= 2%)",
                f"- Automatic grounding check passed: {stats['auto_grounded_pct']:.1f}%",
                "",
            ]
        ),
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Explanation audit")
    sub = parser.add_subparsers(dest="command", required=True)
    sample = sub.add_parser("sample", help="draw explanations to rate")
    sample.add_argument("--n", type=int, default=100)
    sample.add_argument("--out", type=Path, default=Path("audit.csv"))
    scored = sub.add_parser("score", help="compute kappa from completed ratings")
    scored.add_argument("csv", type=Path)
    args = parser.parse_args()

    if args.command == "sample":
        rows = draw_sample(args.n)
        with open(args.out, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
        print(f"wrote {len(rows)} explanations to {args.out}; rate them independently, then score")
        return 0
    with open(args.csv, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    try:
        stats = score(rows)
    except ValueError as err:
        print(f"error: {err}", file=sys.stderr)
        return 1
    write_report(stats, args.csv)
    print(f"kappa {stats['kappa']:.3f}; wrote {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
